// Generates libs/backseat/lines_data.cpp in the CoMaps fork from the TypeScript line library,
// so the roast lines have one source of truth. Run from this repo's root:
//   node core/tools/gen-lines.ts ../backseat-driver-comaps/libs/backseat/lines_data.cpp
import { writeFileSync } from "node:fs";
import { LINES } from "../../engine/src/lines.ts";

const lit = (s: string) => JSON.stringify(s); // JSON string escapes are valid C++ for these lines
let out = `// Generated by backseat-driver/core/tools/gen-lines.ts from engine/src/lines.ts. Do not edit by hand.\n`;
out += `#include "backseat/lines_data.hpp"\n\nnamespace backseat\n{\nLineTable const & LineData()\n{\n  static LineTable const table = {\n`;
for (const [key, tiers] of Object.entries(LINES)) {
  out += `    {${lit(key)},\n     {{\n`;
  for (const tier of tiers) out += `       {${tier.map(lit).join(",\n        ")}},\n`;
  out += `     }}},\n`;
}
out += `  };\n  return table;\n}\n}  // namespace backseat\n`;
const target = process.argv[2];
if (!target) throw new Error("usage: node core/tools/gen-lines.ts <path/to/lines_data.cpp>");
writeFileSync(target, out);
console.log(`wrote ${Object.keys(LINES).length} keys`);
